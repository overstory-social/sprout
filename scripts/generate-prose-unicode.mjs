// Writes runtime-c/src/prose/unicode.c: the two Unicode rules the TypeScript prose layer takes
// from the JavaScript runtime, as tables the C runtime reads (the C runtime calls nothing
// from libc, so it holds no locale or Unicode data of its own).
//
//   - which code points are letters or numbers (`/[\p{L}\p{N}]/u`), the opening a capital
//     goes past (prose/reflow.ts `capitalise`);
//   - what `String.prototype.toUpperCase` makes of each code point of the Basic
//     Multilingual Plane, special casing included, since `capitalise` upper-cases the one
//     UTF-16 code unit it lands on.
//
// `node scripts/generate-prose-unicode.mjs` rewrites the file. The tables follow the Unicode
// version of the Node that wrote them (named at the head of the file); the prose goldens
// (corpus/goldens/prose.json) pin both rules over every edge of every range.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FILE = fileURLToPath(new URL('../runtime-c/src/prose/unicode.c', import.meta.url));
const LAST = 0x10ffff;
const surrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;

const runs = [];
for (let cp = 0; cp <= LAST; cp++) {
  if (surrogate(cp) || !/^[\p{L}\p{N}]$/u.test(String.fromCodePoint(cp))) continue;
  const last = runs.at(-1);
  if (last !== undefined && last[1] === cp - 1) last[1] = cp;
  else runs.push([cp, cp]);
}

const upper = [];
for (let cp = 0; cp <= 0xffff; cp++) {
  if (surrogate(cp)) continue;
  const letter = String.fromCodePoint(cp);
  const made = letter.toUpperCase();
  if (made === letter) continue;
  const units = [...made].map((one) => one.codePointAt(0));
  if (units.length > 3 || units.some((unit) => unit > 0xffff)) {
    throw new Error(`U+${cp.toString(16)} upper-cases to more than three BMP code points.`);
  }
  upper.push([cp, ...units, ...Array(3 - units.length).fill(0)]);
}

const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;
const wrap = (items, per) => {
  const rows = [];
  for (let i = 0; i < items.length; i += per) rows.push(`  ${items.slice(i, i + per).join(', ')},`);
  return rows.join('\n');
};

const text = `/*
 * Generated by scripts/generate-prose-unicode.mjs from Node ${process.version}
 * (Unicode ${process.versions.unicode}); do not edit by hand. Two rules of the
 * JavaScript runtime that prose's capitalising takes (the spec's Prose > Slots), held
 * as tables because the runtime calls nothing from libc.
 */
#include "prose/unicode.h"

/* The runs of code points that are letters or numbers (\\p{L} and \\p{N}), first and last. */
static const unsigned long LETTER_RUNS[][2] = {
${wrap(runs.map(([first, last]) => `{0x${first.toString(16).toUpperCase()}, 0x${last.toString(16).toUpperCase()}}`), 4)}
};

/* Each code point of the Basic Multilingual Plane whose upper case is something else, with that as up to three code points. */
static const unsigned short UPPER_CASE[][4] = {
${wrap(upper.map((row) => `{${row.map(hex).join(', ')}}`), 3)}
};

#define COUNT(table) (sizeof(table) / sizeof((table)[0]))

bool prose_unicode_letter_or_number(unsigned long cp) {
  size_t low = 0, high = COUNT(LETTER_RUNS);
  while (low < high) {
    size_t middle = low + (high - low) / 2;
    if (cp < LETTER_RUNS[middle][0]) high = middle;
    else if (cp > LETTER_RUNS[middle][1]) low = middle + 1;
    else return true;
  }
  return false;
}

size_t prose_unicode_upper(unsigned long cp, unsigned long out[3]) {
  size_t low = 0, high = COUNT(UPPER_CASE), n = 0;
  if (cp > 0xFFFF) {
    out[0] = cp;
    return 1;
  }
  while (low < high) {
    size_t middle = low + (high - low) / 2;
    if (cp < UPPER_CASE[middle][0]) high = middle;
    else if (cp > UPPER_CASE[middle][0]) low = middle + 1;
    else {
      size_t i;
      for (i = 1; i < 4 && UPPER_CASE[middle][i] != 0; i++) out[n++] = UPPER_CASE[middle][i];
      return n;
    }
  }
  out[0] = cp;
  return 1;
}
`;

writeFileSync(FILE, text);
console.log(`wrote ${FILE}: ${runs.length} runs, ${upper.length} upper-case entries`);
