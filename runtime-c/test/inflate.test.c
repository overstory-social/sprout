/* The text every non-empty vector holds. */
static size_t sample(char *out) {
  static const char *const words[] = {"lamp", "press", "cellar", "brass", "key", "shelf", "oak", "door", "quartz", "jinx", "zebra", "a", "the"};
  size_t at = 0;
  for (int i = 0; i < 90; i++) {
    const char *w = words[(i * i + 3 * i) % 13];
    size_t n = strlen(w);
    memcpy(out + at, w, n);
    at += n;
    if (i % 7 == 0) out[at++] = '.';
    out[at++] = ' ';
  }
  out[at] = '\0';
  return at;
}

static void inflate_vector(const unsigned char *gz, size_t length, bool sample_text) {
  test_heap heap;
  sprout_host host = test_host(&heap);
  sprout_arena arena;
  char expected[1024];
  char *out;
  size_t out_length;
  const char *why;
  sprout_arena_init(&arena, &host);
  CHECK_INT(sprout_gunzip(&arena, gz, length, &out, &out_length, &why), SPROUT_OK);
  if (sample_text) {
    size_t n = sample(expected);
    CHECK_BYTES(out, out_length, expected);
    CHECK_INT(out_length, n);
  } else {
    CHECK_INT(out_length, 0);
  }
  sprout_arena_reset(&arena);
  CHECK_INT(heap.pages, 0);
}

static void a_dynamic_block_inflates(void) { inflate_vector(GZ_DYNAMIC, sizeof GZ_DYNAMIC, true); }
static void a_fixed_block_inflates(void) { inflate_vector(GZ_FIXED, sizeof GZ_FIXED, true); }
static void a_stored_block_inflates(void) { inflate_vector(GZ_STORED, sizeof GZ_STORED, true); }
static void an_empty_member_inflates_to_nothing(void) {
  inflate_vector(GZ_EMPTY, sizeof GZ_EMPTY, false);
}

static void refused(const unsigned char *gz, size_t length, const char *words) {
  test_heap heap;
  sprout_host host = test_host(&heap);
  sprout_arena arena;
  char *out;
  size_t out_length;
  const char *why = NULL;
  sprout_arena_init(&arena, &host);
  CHECK_INT(sprout_gunzip(&arena, gz, length, &out, &out_length, &why), SPROUT_BAD_INPUT);
  CHECK(out == NULL);
  CHECK(why != NULL);
  if (why != NULL && words != NULL) CHECK_STR(why, words);
  sprout_arena_reset(&arena);
}

static void a_flipped_byte_fails_the_checksum(void) {
  unsigned char copy[sizeof GZ_STORED];
  memcpy(copy, GZ_STORED, sizeof copy);
  copy[40] ^= 0x01;
  refused(copy, sizeof copy, "the compressed data does not match its checksum");
}

static void a_truncated_stream_is_refused_in_words(void) {
  refused(GZ_DYNAMIC, sizeof GZ_DYNAMIC - 20, NULL); /* the trailer is then whatever bytes were left */
}

static void a_stream_that_is_not_gzip_is_refused(void) {
  unsigned char copy[sizeof GZ_FIXED];
  memcpy(copy, GZ_FIXED, sizeof copy);
  copy[0] = 0x00;
  refused(copy, sizeof copy, "the data is not gzip: it does not begin with its magic number");
}

static void a_stream_longer_than_its_trailer_says_is_refused(void) {
  unsigned char copy[sizeof GZ_STORED];
  memcpy(copy, GZ_STORED, sizeof copy);
  copy[sizeof copy - 4] = 5; /* ISIZE */
  copy[sizeof copy - 3] = 0;
  refused(copy, sizeof copy, "the compressed data is longer than it says");
}

static void every_truncation_of_a_vector_is_refused_without_overrun(void) {
  const unsigned char *vectors[] = {GZ_DYNAMIC, GZ_FIXED, GZ_STORED};
  size_t sizes[] = {sizeof GZ_DYNAMIC, sizeof GZ_FIXED, sizeof GZ_STORED};
  for (int v = 0; v < 3; v++) {
    for (size_t cut = 0; cut < sizes[v]; cut++) {
      test_heap heap;
      sprout_host host = test_host(&heap);
      sprout_arena arena;
      char *out;
      size_t out_length;
      const char *why = NULL;
      sprout_arena_init(&arena, &host);
      CHECK_INT(sprout_gunzip(&arena, vectors[v], cut, &out, &out_length, &why), SPROUT_BAD_INPUT);
      CHECK(why != NULL);
      sprout_arena_reset(&arena);
    }
  }
}

static void the_crc_is_the_gzip_polynomials(void) {
  CHECK_INT(sprout_crc32(0, (const unsigned char *)"123456789", 9), 0xCBF43926u);
  CHECK_INT(sprout_crc32(0, (const unsigned char *)"", 0), 0);
}

static void a_dynamic_block_gzip_of_the_stored_golden_reads_back_byte_for_byte(void) {
  test_heap heap;
  sprout_host host = test_host(&heap);
  sprout_arena arena;
  size_t gz_length, json_length, out_length;
  unsigned char *gz = (unsigned char *)test_golden("stored-canon.json.gz", &gz_length);
  char *json = test_golden("stored-canon.json", &json_length);
  char *out = NULL;
  const char *why = NULL;
  sprout_arena_init(&arena, &host);
  CHECK_INT(sprout_gunzip(&arena, gz, gz_length, &out, &out_length, &why), SPROUT_OK);
  CHECK_INT(out_length, json_length);
  CHECK(out != NULL && memcmp(out, json, json_length) == 0);
  gz[gz_length / 2] ^= 0x55;
  CHECK_INT(sprout_gunzip(&arena, gz, gz_length, &out, &out_length, &why), SPROUT_BAD_INPUT);
  sprout_arena_reset(&arena);
  free(gz);
  free(json);
}

